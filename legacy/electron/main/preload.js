const { contextBridge, ipcRenderer } = require('electron')

contextBridge.exposeInMainWorld('kaki', {
  getHistory: () => ipcRenderer.invoke('history:get'),
  searchHistory: query => ipcRenderer.invoke('history:search', String(query || '')),
  getThumbnail: id => ipcRenderer.invoke('history:thumb', id),
  diagnostic: message => ipcRenderer.send('renderer:diagnostic', String(message)),
  activate: (id, opts) => ipcRenderer.send('item:activate', id, opts || {}),
  remove: id => ipcRenderer.send('item:delete', id),
  togglePin: id => ipcRenderer.send('item:pin', id),
  updateMetadata: payload => ipcRenderer.send('item:metadata', payload),
  hide: () => ipcRenderer.send('panel:hide'),
  quit: () => ipcRenderer.send('app:quit'),
  getSettings: () => ipcRenderer.invoke('settings:get'),
  saveShortcuts: payload => ipcRenderer.invoke('settings:save-shortcuts', payload),
  desklinkHost: payload => ipcRenderer.invoke('desklink:host', payload || {}),
  desklinkConnect: payload => ipcRenderer.invoke('desklink:connect', payload || {}),
  desklinkStop: () => ipcRenderer.invoke('desklink:stop'),
  desklinkSetLayout: (name, col, row) => ipcRenderer.invoke('desklink:set-layout', { name, col, row }),
  copyText: text => ipcRenderer.invoke('clipboard:write', String(text ?? '')),
  onDesklinkStatus: cb => ipcRenderer.on('desklink:status', (_e, value) => cb(value)),
  onDesklinkError: cb => ipcRenderer.on('desklink:error', (_e, value) => cb(value)),
  recordShortcut: target => ipcRenderer.send('settings:record-shortcut', target),
  onShortcutRecorded: cb => ipcRenderer.on('shortcut:recorded', (_e, result) => cb(result)),
  clearHistory: () => ipcRenderer.send('history:clear'),
  itemContext: (id, currentBoard) => ipcRenderer.send('item:context', id, currentBoard || null),
  boardContext: name => ipcRenderer.send('board:context', name),
  createBoard: payload => ipcRenderer.send('board:create', payload),
  renameBoard: payload => ipcRenderer.send('board:rename', payload),
  onUpdate: cb => ipcRenderer.on('history:updated', (_e, data) => cb(data)),
  onShown: cb => ipcRenderer.on('panel-shown', (_e, data) => cb(data)),
  onHidden: cb => ipcRenderer.on('panel-hidden', () => cb()),
  onBoardPrompt: cb => ipcRenderer.on('board:prompt', (_e, payload) => cb(payload)),
  onItemMetadata: cb => ipcRenderer.on('item:metadata:open', (_e, payload) => cb(payload)),
})
