import Foundation
import AppKit
import UniformTypeIdentifiers

@MainActor
final class ClipboardService {
    private let store: HistoryStore
    private let pasteboard: NSPasteboard
    private let sourceMarker = UUID().uuidString
    private let sourceType = NSPasteboard.PasteboardType("com.kakitools.source")
    private var timer: Timer?
    private var lastChangeCount = -1
    private let ignoredTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"), .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType")
    ]
    init(store: HistoryStore, pasteboard: NSPasteboard = .general) { self.store = store; self.pasteboard = pasteboard }
    func start(interval: TimeInterval = 0.12) {
        stop(); captureNow()
        let timer = Timer(timeInterval: max(0.08, interval), repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.captureNow() }
        }
        self.timer = timer
        RunLoop.main.add(timer, forMode: .common)
    }
    func stop() { timer?.invalidate(); timer = nil }
    func captureNow() {
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        if pasteboard.string(forType: sourceType) == sourceMarker || !(Set(pasteboard.types ?? []).intersection(ignoredTypes)).isEmpty {
            lastChangeCount = count; return
        }
        let text = pasteboard.string(forType: .string)
        let html = pasteboard.string(forType: .html)
        let rtfData = pasteboard.data(forType: .rtf)
        let imageTypes = (pasteboard.types ?? []).filter { UTType($0.rawValue)?.conforms(to: .image) == true }
        let image = imageTypes.lazy.compactMap { self.pasteboard.data(forType: $0) }.first
        // Reading several formats must not combine two successive external copies.
        guard pasteboard.changeCount == count else { return }
        lastChangeCount = count
        if let text, !text.isEmpty { store.addText(text, html: html, rtfData: rtfData) }
        if let image { store.captureImage(data: image) }
    }
    @discardableResult
    func write(item: HistoryItem, plainText: Bool = false) -> Int? {
        let entry = NSPasteboardItem()
        if item.type == "text", let text = item.text {
            entry.setString(text, forType: .string)
            if !plainText {
                if let html = item.html { entry.setString(html, forType: .html) }
                if let rtfData = item.rtfData { entry.setData(rtfData, forType: .rtf) }
                else if let rtf = item.rtf { entry.setData(Data(rtf.utf8), forType: .rtf) }
            }
        } else if item.type == "image", let current = store.item(id: item.id), let file = current.file,
                  let data = try? Data(contentsOf: URL(fileURLWithPath: file), options: .mappedIfSafe) {
            entry.setData(data, forType: .png)
        } else { return nil }
        entry.setString(sourceMarker, forType: sourceType)
        pasteboard.clearContents()
        guard pasteboard.writeObjects([entry]) else { return nil }
        let count = pasteboard.changeCount
        lastChangeCount = count
        return count
    }
    @discardableResult
    func writeImage(_ data: Data) -> Int? {
        let entry = NSPasteboardItem()
        entry.setData(data, forType: .png)
        entry.setString(sourceMarker, forType: sourceType)
        pasteboard.clearContents()
        guard pasteboard.writeObjects([entry]) else { return nil }
        let count = pasteboard.changeCount
        lastChangeCount = count
        return count
    }
    func matchesWrite(_ count: Int) -> Bool {
        pasteboard.changeCount == count && pasteboard.string(forType: sourceType) == sourceMarker
    }
}
